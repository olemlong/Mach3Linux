# ------------------------------------------------------------- 6. Lutris
GAMES_DIR="$LUTRIS_DATA/games"
[[ ! -d "$GAMES_DIR" && -d "$HOME/.config/lutris/games" ]] && GAMES_DIR="$HOME/.config/lutris/games"
mkdir -p "$GAMES_DIR"
CONFIG_NAME="$SLUG-$(date +%s)"
cat > "$GAMES_DIR/$CONFIG_NAME.yml" <<EOF
game:
  exe: $MACH3_DIR/Mach3.exe
  prefix: $PREFIX
  working_dir: $MACH3_DIR
system:
  env:
    LD_PRELOAD: $FORCEBCAST
wine:
  version: $WINE_VERSION
  graphics_driver: x11
  dxvk: false
  vkd3d: false
  d3d_extras: false
  dxvk_nvapi: false
  fsr: false
  battleye: false
  eac: false
EOF

python3 - "$LUTRIS_DATA/pga.db" "$SLUG" "$PREFIX" "$CONFIG_NAME" <<'PY'
import sqlite3, sys, time
db, slug, prefix, cfg = sys.argv[1:5]
con = sqlite3.connect(db)
cols = {r[1] for r in con.execute("pragma table_info(games)")}
g = {"name": "Mach3", "slug": slug, "runner": "wine", "platform": "Windows",
     "directory": prefix, "installed": 1, "installed_at": int(time.time()), "configpath": cfg}
g = {k: v for k, v in g.items() if k in cols}
old = con.execute("select id from games where slug=?", (slug,)).fetchone()
if old:
    con.execute(f"update games set {', '.join(k+'=?' for k in g)} where id=?", (*g.values(), old[0]))
else:
    con.execute(f"insert into games ({', '.join(g)}) values ({', '.join('?'*len(g))})", tuple(g.values()))
con.commit()
PY
info "Mach3 has been added to Lutris."

