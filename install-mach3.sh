#!/usr/bin/env bash
# =============================================================================
#  install-mach3.sh — Mach3 + Ethernet SmoothStepper on Bazzite/Fedora via Lutris
# =============================================================================
#  What the script does:
#    1. Finds (or downloads) Wine-staging for Lutris
#    2. Creates a dedicated Wine prefix for Mach3
#    3. Installs gdiplus, mfc42 and vcrun6 with Winetricks
#    4. Runs the Mach3 installer (you click through it)
#    5. Installs the ESS plugin (ESS.dll) and an optional license file
#       + allows port 69 (TFTP) and broadcast, which the ESS plugin needs
#    6. Adds Mach3 to Lutris with the right settings
#       (X11, DXVK/VKD3D off – required for Mach3 to draw correctly)
#    7. Optionally configures the network card facing the ESS (10.9.9.9)
#
#  You must download these yourself (put them in ~/Downloads):
#    - The Mach3 installer  (Mach3Version*.exe)        from machsupport.com
#    - ESS plugin for Mach3 (ESS.dll, .zip or .m3p)    from warp9td.com
#    - (optional) the license file Mach1Lic.dat
#
#  Usage:
#    chmod +x install-mach3.sh
#    ./install-mach3.sh             full installation
#    ./install-mach3.sh --network   only configure the network card facing the ESS
#
#  Options (environment variables):
#    MACH3_INSTALLER=/path/to/Mach3.exe   ESS_PLUGIN=/path/to/ESS.dll|.zip
#    MACH3_LICENSE=/path/to/Mach1Lic.dat  PREFIX=~/Games/mach3
#    ESS_IFACE=enp3s0   (network card facing the ESS – skips the question)
# =============================================================================
set -euo pipefail

PREFIX="${PREFIX:-$HOME/Games/mach3}"
DOWNLOADS="${XDG_DOWNLOAD_DIR:-$HOME/Downloads}"
LUTRIS_DATA="${XDG_DATA_HOME:-$HOME/.local/share}/lutris"
WINE_RUNNERS="$LUTRIS_DATA/runners/wine"
ESS_IP="10.9.9.9"
PC_IP="10.9.9.1/24"
SLUG="mach3"

bold=$(tput bold 2>/dev/null || true); norm=$(tput sgr0 2>/dev/null || true)
info() { echo "${bold}==>${norm} $*"; }
warn() { echo "${bold}WARNING:${norm} $*" >&2; }
die()  { echo "${bold}ERROR:${norm} $*" >&2; exit 1; }
ask()  { local a; read -r -p "$1 [y/N] " a; [[ "$a" =~ ^[Yy] ]]; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

# ------------------------------------------------------------- network (functions)
setup_network() {
    local iface="$1"
    info "Configuring $iface: static IP ${PC_IP%/*}, firewall zone trusted ..."
    if nmcli -t -f NAME con show | grep -qx "ESS"; then
        nmcli con mod ESS connection.interface-name "$iface" ipv4.method manual \
            ipv4.addresses "$PC_IP" ipv4.gateway "" ipv6.method disabled connection.zone trusted
    else
        nmcli con add type ethernet ifname "$iface" con-name ESS ipv4.method manual \
            ipv4.addresses "$PC_IP" ipv6.method disabled connection.zone trusted >/dev/null
    fi
    nmcli con up ESS >/dev/null || warn "Could not activate the connection."
    if ping -c 3 -W 2 "$ESS_IP" >/dev/null; then info "The ESS responds at $ESS_IP!"
    else warn "The ESS does not respond at $ESS_IP – check the cable, power and that the right card was chosen."; fi
}

# Shows a numbered list of wired network cards and lets the user pick one.
# The result is stored in $CHOSEN_IFACE.
choose_iface() {
    CHOSEN_IFACE=""
    local devs=() d i n def="" inet_dev carrier link ip note
    mapfile -t devs < <(nmcli -t -f DEVICE,TYPE device status | awk -F: '$2=="ethernet"{print $1}')
    if (( ${#devs[@]} == 0 )); then
        warn "No wired network cards found. Connect the ESS and try again with: $0 --network"
        return 1
    fi
    inet_dev=$(ip route show default 2>/dev/null | awk '{for(i=1;i<NF;i++) if($i=="dev"){print $(i+1); exit}}')

    echo
    echo "${bold}Which network card is the ESS connected to?${norm}"
    for i in "${!devs[@]}"; do
        d=${devs[$i]}
        carrier=$(cat "/sys/class/net/$d/carrier" 2>/dev/null || echo 0)
        if [[ "$carrier" == 1 ]]; then link="cable connected"; else link="no cable"; fi
        ip=$(ip -4 -o addr show "$d" 2>/dev/null | awk '{print $4}' | head -n1)
        note=""
        [[ "$d" == "$inet_dev" ]] && note="  (used for internet – probably not this one)"
        printf "  %d) %-14s %-16s %-18s%s\n" $((i+1)) "$d" "$link" "${ip:-}" "$note"
        # Default: the first card with a cable that is not the internet card
        if [[ -z "$def" && "$carrier" == 1 && "$d" != "$inet_dev" ]]; then def=$((i+1)); fi
    done
    echo "  0) Skip"
    [[ -z "$def" ]] && def=1

    while true; do
        read -r -p "Choose a number [$def]: " n
        n=${n:-$def}
        if [[ "$n" == 0 ]]; then return 1; fi
        if [[ "$n" =~ ^[0-9]+$ ]] && (( n >= 1 && n <= ${#devs[@]} )); then
            CHOSEN_IFACE=${devs[$((n-1))]}
            if [[ "$CHOSEN_IFACE" == "$inet_dev" ]] && ! ask "$CHOSEN_IFACE is used for internet. Are you sure?"; then
                continue
            fi
            return 0
        fi
        echo "Invalid choice."
    done
}

network_step() {
    command -v nmcli >/dev/null || { warn "nmcli is missing – configure the network manually."; return; }
    if [[ -n "${ESS_IFACE:-}" ]]; then
        setup_network "$ESS_IFACE"
    elif choose_iface; then
        setup_network "$CHOSEN_IFACE"
    else
        info "Skipping network setup. Run later: $0 --network"
    fi
}

if [[ "${1:-}" == "--network" ]]; then
    [[ $EUID -eq 0 ]] && die "Do not run this script with sudo."
    network_step; exit 0
fi

# ----------------------------------------------------------------- checks
[[ $EUID -eq 0 ]] && die "Do not run this script with sudo. Run it as your normal user: ./install-mach3.sh"
command -v lutris  >/dev/null || die "Lutris is not installed (as a regular package). Install it and run the script again."
command -v python3 >/dev/null || die "python3 is missing."
pgrep -f 'python[0-9.]* [^ ]*bin/lutris' >/dev/null && die "Close Lutris before running the script."
[[ -f "$LUTRIS_DATA/pga.db" ]] || die "$LUTRIS_DATA/pga.db not found. Start Lutris once, close it, and run the script again."
[[ -e "$PREFIX" ]] && die "$PREFIX already exists. Move or delete it first (or set PREFIX=... to another folder)."

find_file() { # $1=value from env variable  $2..=glob patterns in Downloads
    local given="$1"; shift
    if [[ -n "$given" ]]; then [[ -f "$given" ]] && { echo "$given"; return; }; return 1; fi
    local p f
    for p in "$@"; do
        f=$(ls -t "$DOWNLOADS"/$p 2>/dev/null | head -n1 || true)
        [[ -n "$f" ]] && { echo "$f"; return; }
    done
    return 1
}

MACH3_INSTALLER=$(find_file "${MACH3_INSTALLER:-}" 'Mach3*.exe' 'mach3*.exe') \
    || die "Mach3 installer not found. Download it from machsupport.com to $DOWNLOADS, or set MACH3_INSTALLER=/path/to/file.exe"
ESS_PLUGIN=$(find_file "${ESS_PLUGIN:-}" 'ESS*.dll' 'ESS*.zip' 'ESS*.m3p' 'ess*.zip' 'ess*.m3p') || ESS_PLUGIN=""
MACH3_LICENSE=$(find_file "${MACH3_LICENSE:-}" 'Mach1Lic.dat') || MACH3_LICENSE=""

info "Mach3 installer: $MACH3_INSTALLER"
info "ESS plugin:      ${ESS_PLUGIN:-(not found – can be added later)}"
info "License:         ${MACH3_LICENSE:-(none – Mach3 runs in demo mode)}"
info "Wine prefix:     $PREFIX"
ask "Continue?" || exit 0

# ------------------------------------------------------------- 1. Wine
pick_wine() {
    ls -1d "$WINE_RUNNERS"/*staging* 2>/dev/null | grep -vi -e wow64 -e proton | sort -V | tail -n1
}
WINE_DIR=$(pick_wine || true)
if [[ -z "$WINE_DIR" ]]; then
    info "Downloading Wine-staging for Lutris ..."
    url=$(curl -fsSL https://lutris.net/api/runners/wine 2>/dev/null | python3 -c '
import json,sys
v=[x for x in json.load(sys.stdin).get("versions",[])
   if "staging" in x["version"] and "wow64" not in x["version"] and x.get("architecture")=="x86_64"]
print(v[-1]["url"] if v else "")' || true)
    if [[ -n "$url" ]]; then
        mkdir -p "$WINE_RUNNERS"
        curl -fL --progress-bar "$url" -o "$TMP/wine.tar.xz"
        tar -xf "$TMP/wine.tar.xz" -C "$WINE_RUNNERS"
        WINE_DIR=$(pick_wine || true)
    fi
    [[ -n "$WINE_DIR" ]] || die "Could not download Wine. Open Lutris → Preferences → Runners → Wine, install \"wine-staging\", and run the script again."
fi
WINE_VERSION=$(basename "$WINE_DIR")
export WINE="$WINE_DIR/bin/wine" WINESERVER="$WINE_DIR/bin/wineserver" WINEPREFIX="$PREFIX"
[[ -x "$WINE" ]] || die "$WINE not found"
info "Using Wine: $WINE_VERSION"

# ------------------------------------------------------------- 2. prefix
info "Creating Wine prefix ..."
mkdir -p "$(dirname "$PREFIX")"
WINEDLLOVERRIDES="mscoree,mshtml=" "$WINE" wineboot -u >/dev/null 2>&1
"$WINESERVER" -w

# ------------------------------------------------------------- 3. winetricks
WINETRICKS=""
for w in "$LUTRIS_DATA/runtime/winetricks/winetricks" "$(command -v winetricks || true)"; do
    [[ -n "$w" && -x "$w" ]] && { WINETRICKS="$w"; break; }
done
if [[ -z "$WINETRICKS" ]]; then
    info "Downloading Winetricks ..."
    curl -fsSL https://raw.githubusercontent.com/Winetricks/winetricks/master/src/winetricks -o "$TMP/winetricks"
    chmod +x "$TMP/winetricks"; WINETRICKS="$TMP/winetricks"
fi
info "Installing gdiplus, mfc42 and vcrun6 (takes a few minutes) ..."
"$WINETRICKS" -q gdiplus mfc42 vcrun6 || warn "Winetricks reported errors – continuing anyway."
"$WINESERVER" -w

# ------------------------------------------------------------- 4. Mach3
info "Starting the Mach3 installer. Click through it and install to C:\\Mach3."
info "Errors about the parallel port driver can be ignored – it is not needed with the ESS."
"$WINE" "$MACH3_INSTALLER" || true
"$WINESERVER" -w
MACH3_DIR="$PREFIX/drive_c/Mach3"
[[ -f "$MACH3_DIR/Mach3.exe" ]] || die "$MACH3_DIR/Mach3.exe not found. Was Mach3 installed to C:\\Mach3?"

# ------------------------------------------------------------- 5. ESS + license
if [[ -n "$ESS_PLUGIN" ]]; then
    mkdir -p "$MACH3_DIR/PlugIns"
    case "${ESS_PLUGIN,,}" in
        *.dll) cp "$ESS_PLUGIN" "$MACH3_DIR/PlugIns/ESS.dll" ;;
        *.zip|*.m3p)
            python3 - "$ESS_PLUGIN" "$MACH3_DIR/PlugIns" <<'PY' || warn "ESS.dll not found in the archive – copy it to PlugIns manually."
import zipfile, sys, os
z = zipfile.ZipFile(sys.argv[1]); dst = sys.argv[2]
hits = [n for n in z.namelist() if os.path.basename(n).lower() == "ess.dll"]
if not hits: sys.exit(1)
open(os.path.join(dst, "ESS.dll"), "wb").write(z.read(hits[0]))
PY
            ;;
    esac
    [[ -f "$MACH3_DIR/PlugIns/ESS.dll" ]] && info "ESS.dll installed in PlugIns."
else
    warn "No ESS plugin found. Copy ESS.dll to $MACH3_DIR/PlugIns/ later."
fi
[[ -n "$MACH3_LICENSE" ]] && cp "$MACH3_LICENSE" "$MACH3_DIR/" && info "License copied."

# ------------------------------------------------------------- 5b. Linux tweaks for the ESS
# The ESS plugin uses TFTP (port 69) to load firmware into the board. Linux does not let
# regular users bind ports below 1024, so we lower that limit to 69.
info "Allowing port 69 (TFTP) for the ESS – requires your sudo password ..."
echo "net.ipv4.ip_unprivileged_port_start=69" | sudo tee /etc/sysctl.d/99-mach3-ess.conf >/dev/null \
    && sudo sysctl -q net.ipv4.ip_unprivileged_port_start=69 \
    || warn "Could not change the port limit. Run: sudo sysctl net.ipv4.ip_unprivileged_port_start=69"

# The ESS plugin sends broadcast packets without requesting SO_BROADCAST. Windows allows
# that, Linux does not. forcebcast.so is loaded with LD_PRELOAD and enables SO_BROADCAST
# on every UDP socket.
FORCEBCAST="$PREFIX/forcebcast.so"
cat > "$TMP/forcebcast.c" <<'CSRC'
/* forcebcast.so — enables SO_BROADCAST on all UDP sockets (for the ESS plugin under Wine) */
#define _GNU_SOURCE
#include <dlfcn.h>
#include <sys/socket.h>
#include <netinet/in.h>

int socket(int domain, int type, int protocol)
{
    static int (*real_socket)(int, int, int);
    if (!real_socket) real_socket = dlsym(RTLD_NEXT, "socket");
    int fd = real_socket(domain, type, protocol);
    if (fd >= 0 && domain == AF_INET && (type & 0xf) == SOCK_DGRAM) {
        int one = 1;
        setsockopt(fd, SOL_SOCKET, SO_BROADCAST, &one, sizeof one);
    }
    return fd;
}
CSRC
if command -v gcc >/dev/null; then
    info "Building forcebcast.so from source ..."
    gcc -shared -fPIC -O2 -s -o "$FORCEBCAST" "$TMP/forcebcast.c" -ldl
else
